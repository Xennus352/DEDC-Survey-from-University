"""Regression checks for dashboard CRUD, confirmations and persistent navigation."""
from pathlib import Path


def check(page, context, base):
    page.goto(base + "/dashboard/departments")
    page.get_by_role("button", name="Add department", exact=False).click()
    page.locator('select[name="org_type"]').select_option("ministry")
    page.locator('input[name="name"]').fill("Teacher's ministry")
    page.get_by_role("button", name="Create", exact=True).click()
    page.get_by_role("cell", name="Teacher's ministry", exact=True).wait_for()
    row = page.get_by_role("row").filter(has_text="Teacher's ministry")
    row.get_by_role("button", name="Edit", exact=True).click()
    page.locator('input[name="name"]').fill("Teacher's ministry updated")
    page.get_by_role("button", name="Save", exact=True).click()
    page.get_by_role("cell", name="Teacher's ministry updated", exact=True).wait_for()
    page.get_by_role("button", name="Add department", exact=False).click()
    page.locator('select[name="org_type"]').select_option("university")
    page.locator('input[name="name"]').fill("Teacher's university")
    page.get_by_text("University details", exact=True).click()
    page.locator('input[name="uni_type"]').fill("Public")
    page.get_by_role("button", name="Create", exact=True).click()
    page.get_by_role("cell", name="Teacher's university", exact=True).wait_for()
    page.get_by_role("row").filter(has_text="Teacher's university").get_by_role("button", name="Edit", exact=True).click()
    page.locator('input[name="uni_type"]').fill("Private")
    page.get_by_role("button", name="Save", exact=True).click()
    page.get_by_role("cell", name="Private", exact=True).wait_for()
    page.get_by_role("row").filter(has_text="Teacher's university").get_by_role("button", name="Delete", exact=True).click()
    page.get_by_role("dialog").get_by_role("button", name="Cancel", exact=True).click()
    assert page.get_by_role("cell", name="Teacher's university", exact=True).is_visible()
    page.get_by_role("row").filter(has_text="Teacher's university").get_by_role("button", name="Delete", exact=True).click()
    output = Path('/tmp/dedc-dashboard-fixes')
    output.mkdir(exist_ok=True)
    for width in (1440, 768, 390):
        page.set_viewport_size({"width": width, "height": 900})
        page.screenshot(path=str(output / f'delete-{width}.png'), animations='disabled')
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    page.get_by_role("dialog").get_by_role("button", name="Delete university", exact=True).click()
    page.get_by_role("cell", name="Teacher's university", exact=True).wait_for(state="detached")
    page.set_viewport_size({"width": 1440, "height": 900})
    page.evaluate('window.dashboardDocumentMarker = "preserved"')
    page.get_by_role("navigation", name="Admin navigation").get_by_role("link", name="Users & enumerators").click()
    page.get_by_role("button", name="Add user", exact=False).wait_for()
    assert page.evaluate('window.dashboardDocumentMarker') == 'preserved'
    assert not page.locator('body').evaluate('(el) => el.hidden')
    page.get_by_role("button", name="Add user", exact=False).click()
    page.get_by_label("Username", exact=True).fill("dashboard-created-user")
    page.get_by_label("Password", exact=True).fill("dashboard-password")
    page.locator('select[name="role_id"]').select_option(label="University")
    page.get_by_role("button", name="Save user", exact=True).click()
    row = page.get_by_role("row").filter(has_text="dashboard-created-user")
    row.get_by_role("button", name="Edit user", exact=True).click()
    page.get_by_label("Username", exact=True).fill("dashboard-edited-user")
    page.get_by_role("button", name="Save user", exact=True).click()
    page.get_by_role("link", name="dashboard-edited-user", exact=True).wait_for()
    page.go_back()
    page.get_by_role("button", name="Add department", exact=False).wait_for()
    assert page.evaluate('window.dashboardDocumentMarker') == 'preserved'
    token = page.locator('meta[name="csrf-token"]').get_attribute('content')
    identifiers = []
    for name in ('Delete first', 'Delete second'):
        response = context.request.post(base + '/api/admin/forms', headers={'X-CSRF-Token': token}, data={'title': name})
        assert response.status == 201, response.text()
        identifiers.append(response.json()['id'])
    page.get_by_role("navigation", name="Admin navigation").get_by_role("link", name="Survey forms").click()
    for identifier in identifiers:
        page.locator(f'[data-select-form="{identifier}"]').check()
    page.get_by_role("button", name="Delete 2 selected", exact=True).click()
    page.get_by_role("button", name="Cancel", exact=True).click()
    for identifier in identifiers:
        assert page.locator(f'[data-select-form="{identifier}"]').is_checked()
    page.get_by_role("button", name="Delete 2 selected", exact=True).click()
    page.get_by_role("dialog").get_by_role("button", name="Delete 2 forms", exact=True).click()
    for identifier in identifiers:
        page.locator(f'[data-select-form="{identifier}"]').wait_for(state="detached")
    page.go_back()
    page.get_by_role("button", name="Add department", exact=False).wait_for()
    page.get_by_role("row").filter(has_text="Teacher's ministry updated").get_by_role("button", name="Delete", exact=True).click()
    page.get_by_role("button", name="Delete ministry", exact=True).click()
    page.get_by_role("cell", name="Teacher's ministry updated", exact=True).wait_for(state="detached")
    public = context.browser.new_context()
    public_page = public.new_page()
    for path in ('/', '/portal'):
        public_page.goto(base + path)
        assert public_page.locator('body').inner_text()
    public.close()
    page.goto(base + '/dashboard')
    page.locator('#content .stats').wait_for()
    print('PASS: ministry/university CRUD, quoted names, user add/edit, bulk selection and custom confirmation, history navigation without document reload, responsive dialogs, public routes', flush=True)
